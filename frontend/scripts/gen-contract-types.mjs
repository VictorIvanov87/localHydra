// Generates src/contracts/generated/*.ts from ../contracts/schemas (the Python contracts' JSON Schemas).
//   node scripts/gen-contract-types.mjs          rewrite
//   node scripts/gen-contract-types.mjs --check  fail if committed output differs
import { compile } from "json-schema-to-typescript";
import { mkdirSync, readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = resolve(here, "../../contracts/schemas");
const outDir = resolve(here, "../src/contracts/generated");
const check = process.argv.includes("--check");

const manifest = JSON.parse(readFileSync(join(schemaDir, "MANIFEST.json"), "utf8"));
const names = Object.keys(manifest.schemas).sort();

const banner =
  "/* eslint-disable */\n// GENERATED by scripts/gen-contract-types.mjs from contracts/schemas. Do not edit.\n// Change the Python contracts, then follow docs/contracts.md.\n";

const files = new Map();
for (const name of names) {
  const schema = JSON.parse(readFileSync(join(schemaDir, manifest.schemas[name].file), "utf8"));
  const ts = await compile(schema, name, {
    bannerComment: banner,
    additionalProperties: false,
    declareExternallyReferenced: true,
    format: true,
    strictIndexSignatures: true,
  });
  files.set(`${name}.ts`, ts);
}
const index =
  banner +
  `export const CONTRACT_VERSION = ${JSON.stringify(manifest.contract_version)} as const;\n` +
  `export const EVENT_SCHEMA_VERSION = ${manifest.event_schema_version} as const;\n` +
  names.map((n) => `export type { ${n} } from "./${n}";`).join("\n") +
  "\n";
files.set("index.ts", index);

if (check) {
  const problems = [];
  for (const [file, text] of files) {
    const p = join(outDir, file);
    if (!existsSync(p) || readFileSync(p, "utf8") !== text) problems.push(`out of date: ${p}`);
  }
  if (existsSync(outDir)) {
    for (const f of readdirSync(outDir)) {
      if (!files.has(f)) problems.push(`unexpected file: ${join(outDir, f)}`);
    }
  }
  if (problems.length) {
    console.error(problems.join("\n"));
    console.error("Run: npm run contracts:generate (see docs/contracts.md)");
    process.exit(1);
  }
  console.log(`contract types OK: ${files.size} files match schemas (contract ${manifest.contract_version})`);
} else {
  mkdirSync(outDir, { recursive: true });
  for (const [file, text] of files) writeFileSync(join(outDir, file), text);
  console.log(`wrote ${files.size} files to ${outDir}`);
}
